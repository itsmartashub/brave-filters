import { cssToFilters } from './css-to-filters.js'

const SOURCE_DIR = new URL(
  '../src/styles/',
  import.meta.url,
)

const OUTPUT_FILE = new URL(
  '../filters',
  import.meta.url,
)

async function collectJavaScriptFiles(directory) {
  const files = []

  for await (const entry of Deno.readDir(directory)) {
    const entryUrl = new URL(
      entry.isDirectory
        ? `${entry.name}/`
        : entry.name,
      directory,
    )

    if (entry.isDirectory) {
      files.push(
        ...(await collectJavaScriptFiles(entryUrl)),
      )

      continue
    }

    if (
      entry.isFile &&
      entry.name.endsWith('.js')
    ) {
      files.push(entryUrl)
    }
  }

  return files
}

async function loadStyleModule(file) {
  try {
    const url = new URL(file.href)

    // Prevent Deno's module cache from returning stale source when using the watch task.
    url.searchParams.set(
      't',
      Date.now().toString(),
    )

    return await import(url.href)
  } catch (error) {
    throw new Error(
      `Failed to import ${file.pathname}\n\n${error.message}`,
      {
        cause: error,
      },
    )
  }
}

function validateStyleModule(module, file) {
  const style = module.default

  if (!style || typeof style !== 'object') {
    throw new Error(
      `${file.pathname}: default export must be an object`,
    )
  }

  if (
    typeof style.name !== 'string' ||
    !style.name.trim()
  ) {
    throw new Error(
      `${file.pathname}: "name" must be a non-empty string`,
    )
  }

  if (
    !Array.isArray(style.domains) ||
    style.domains.length === 0
  ) {
    throw new Error(
      `${file.pathname}: "domains" must be a non-empty array`,
    )
  }

  const domains = style.domains.map(domain => {
    if (
      typeof domain !== 'string' ||
      !domain.trim()
    ) {
      throw new Error(
        `${file.pathname}: every domain must be a non-empty string`,
      )
    }

    const normalizedDomain = domain.trim()

    if (
      normalizedDomain.includes('://') ||
      normalizedDomain.includes('/') ||
      /\s/.test(normalizedDomain)
    ) {
      throw new Error(
        `${file.pathname}: invalid domain "${domain}"`,
      )
    }

    return normalizedDomain
  })

  if (
    typeof style.css !== 'string' ||
    !style.css.trim()
  ) {
    throw new Error(
      `${file.pathname}: "css" must be a non-empty string`,
    )
  }

  return {
    name: style.name.trim(),
    domains,
    css: style.css,
  }
}

function formatSection(name, filters) {
  return [
    `! ${name}`,
    ...filters,
    '',
  ].join('\n')
}

function createOutput(sections) {
  return [
    '! THIS FILE IS GENERATED.',
    '! DO NOT EDIT IT DIRECTLY.',
    '',
    ...sections,
  ]
    .join('\n')
    .trimEnd() + '\n'
}

async function build() {
  const files = await collectJavaScriptFiles(
    SOURCE_DIR,
  )

  files.sort((a, b) =>
    a.pathname.localeCompare(b.pathname),
  )

  const filterSet = new Set()
  const sections = []

  let stylesProcessed = 0
  let filtersGenerated = 0
  let filtersRemovedAsDuplicates = 0

  for (const file of files) {
    const module = await loadStyleModule(file)

    const style = validateStyleModule(
      module,
      file,
    )

    let generatedFilters

    try {
      generatedFilters = await cssToFilters(
        style.css,
        style.domains,
      )
    } catch (error) {
      throw new Error(
        `Failed to process CSS in ${file.pathname}\n\n${error.message}`,
        {
          cause: error,
        },
      )
    }

    if (!Array.isArray(generatedFilters)) {
      throw new Error(
        `${file.pathname}: cssToFilters() must return an array`,
      )
    }

    if (generatedFilters.length === 0) {
      throw new Error(
        `${file.pathname}: CSS produced no filters`,
      )
    }

    stylesProcessed++

    const uniqueFilters = []

    for (const filter of generatedFilters) {
      if (
        typeof filter !== 'string' ||
        !filter.trim()
      ) {
        throw new Error(
          `${file.pathname}: generator produced an invalid filter`,
        )
      }

      filtersGenerated++

      if (filterSet.has(filter)) {
        filtersRemovedAsDuplicates++
        continue
      }

      filterSet.add(filter)
      uniqueFilters.push(filter)
    }

    // The entire style may consist only of filters that were already generated by another source file.
    if (uniqueFilters.length === 0) {
      continue
    }

    sections.push(
      formatSection(
        style.name,
        uniqueFilters,
      ),
    )
  }

  const output = createOutput(sections)

  await Deno.writeTextFile(
    OUTPUT_FILE,
    output,
  )

  console.log('')
  console.log('Build complete.')
  console.log(`Styles: ${stylesProcessed}`)
  console.log(`Filters: ${filterSet.size}`)
  console.log(`Duplicates removed: ${filtersRemovedAsDuplicates}`)
  console.log(`Output: ${OUTPUT_FILE.pathname}`)
}

if (import.meta.main) {
  await build()
}
